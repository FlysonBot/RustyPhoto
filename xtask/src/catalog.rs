//! Catalog coverage: which target features exist as commands.
//! Writes docs/generated/coverage.md and enforces catalog/floor.txt
//! (the live count may only go up).

use crate::Result;
use std::collections::BTreeMap;
use std::path::Path;

const OUT: &str = "docs/generated/coverage.md";
const FLOOR: &str = "catalog/floor.txt";

pub fn run(root: &Path, check: bool) -> Result {
    let catalog = editor_catalog::load()?;
    let specs = editor_engine::command_specs();

    // Every command must have a catalog entry, so nothing is built off-plan.
    let mut problems = Vec::new();
    let mut seen = std::collections::BTreeSet::new();
    for spec in &specs {
        if !seen.insert(spec.id) {
            problems.push(format!("command id `{}` is registered twice", spec.id));
        }
        if !catalog.iter().any(|e| e.id == spec.id) {
            problems.push(format!(
                "command `{}` has no entry in catalog/catalog.toml",
                spec.id
            ));
        }
    }
    if !problems.is_empty() {
        return Err(problems.join("\n  "));
    }

    let is_live = |id: &str| specs.iter().any(|s| s.id == id);
    let live = catalog.iter().filter(|e| is_live(&e.id)).count();
    let total = catalog.len();

    let floor_text =
        std::fs::read_to_string(root.join(FLOOR)).map_err(|e| format!("{FLOOR}: {e}"))?;
    let floor: usize = floor_text
        .trim()
        .parse()
        .map_err(|e| format!("{FLOOR}: not a number ({e})"))?;
    if live < floor {
        return Err(format!(
            "only {live} catalog features are live, below the floor of {floor} in {FLOOR}. \
             Something that worked was removed. Restore it; lowering the floor needs the owner's approval."
        ));
    }

    let report = render(&catalog, &is_live, live, total, floor);
    let path = root.join(OUT);
    if check {
        let current = std::fs::read_to_string(&path).unwrap_or_default();
        if normalize(&current) != normalize(&report) {
            return Err(format!(
                "{OUT} is out of date. Run `cargo xtask catalog` and commit the result."
            ));
        }
    } else {
        std::fs::write(&path, &report).map_err(|e| format!("{OUT}: {e}"))?;
        println!("wrote {OUT}");
    }
    println!("catalog: {live} of {total} live (floor {floor})");
    if live > floor {
        println!("note: raise {FLOOR} to {live} in this PR so it can't slip back");
    }
    Ok(())
}

fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n").trim_end().to_string()
}

fn render(
    catalog: &[editor_catalog::Entry],
    is_live: &dyn Fn(&str) -> bool,
    live: usize,
    total: usize,
    floor: usize,
) -> String {
    let mut out = String::new();
    out.push_str("# Catalog coverage\n\n");
    out.push_str("GENERATED by `cargo xtask catalog`. Do not edit by hand.\n\n");
    out.push_str(&format!(
        "**{live} of {total}** catalog features are live (floor: {floor}).\n\n"
    ));

    let mut groups: BTreeMap<String, Vec<&editor_catalog::Entry>> = BTreeMap::new();
    for e in catalog {
        let group = if e.menu.is_empty() {
            format!("({}s)", e.kind)
        } else {
            e.menu.split('/').next().unwrap_or("").to_string()
        };
        groups.entry(group).or_default().push(e);
    }
    out.push_str("| Area | Live | Total |\n| --- | --- | --- |\n");
    for (group, entries) in &groups {
        let n = entries.iter().filter(|e| is_live(&e.id)).count();
        out.push_str(&format!("| {group} | {n} | {} |\n", entries.len()));
    }
    out.push_str("\n## Missing\n\n");
    for e in catalog.iter().filter(|e| !is_live(&e.id)) {
        let place = if e.menu.is_empty() {
            e.kind.as_str()
        } else {
            e.menu.as_str()
        };
        out.push_str(&format!("- `{}`: {} ({})\n", e.id, e.label, place));
    }
    out
}
